export function formatDate(date: string, lang: Lang, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short" }) {
  return new Intl.DateTimeFormat(lang === "de" ? "de-CH" : "en-GB", opts).format(new Date(date + "T12:00:00"))
}

export function formatNumber(n: number, lang: Lang, digits = 1) {
  return new Intl.NumberFormat(lang === "de" ? "de-CH" : "en-GB", { maximumFractionDigits: digits }).format(n)
}
